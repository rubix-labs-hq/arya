#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** The same pure DSP/validation code, with a chunked JSON/base64 JSC bridge. */
export function bundleMusic(source) {
  if (/^\s*import\b/m.test(source)) throw new Error('Music module must have no platform dependencies')
  const exports = [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map(m => m[1])
  const plain = source.replace(/^export /gm, '')
  return `// Generated by bundle-music.mjs from the shared original score renderer.\nvar AryaMusic = (function () {\n'use strict'\n${plain}\nlet first, second, meter, measurement\nreturn Object.freeze({
  startJSON(text) {
    first = createMusicRenderer(JSON.parse(text)); second = null; meter = musicMeasurement(); measurement = null
    return JSON.stringify({ score: first.score, frames: first.frames, sampleRate: first.sampleRate, channels: first.channels, renderer: MUSIC_RENDERER })
  },
  measureNextJSON() {
    if (!first) throw new Error('Start a score first')
    if (second) return JSON.stringify({ done: true, measurement })
    const pcm = first.renderChunk()
    if (pcm.length) { meter.add(pcm); return JSON.stringify({ done: false }) }
    measurement = meter.result(); second = createMusicRenderer(first.score)
    return JSON.stringify({ done: true, measurement })
  },
  headerBase64() { if (!second) throw new Error('Measure the complete score first'); return musicBase64(musicWAVHeader(first.frames)) },
  nextPCMBase64() { if (!second) throw new Error('Measure the complete score first'); return musicBase64(musicPCM24(second.renderChunk(), measurement.gain)) },
  placementOpsJSON(project, body, receipt) { return JSON.stringify(musicPlacementOps(JSON.parse(project), JSON.parse(body), receipt ? JSON.parse(receipt) : undefined)) },
  assetRecordJSON(score, receipt) { return JSON.stringify(musicAssetRecord(JSON.parse(score), JSON.parse(receipt))) },
  importDecisionJSON(existing, probed, identity) { return JSON.stringify(musicImportDecision(JSON.parse(existing), JSON.parse(probed), identity ? JSON.parse(identity) : null)) },
  exports: Object.freeze({ ${exports.join(', ')} })
})\n})()\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), at = args.indexOf('--out'), srcAt = args.indexOf('--source')
  if (at < 0 || !args[at + 1]) throw new Error('usage: bundle-music.mjs --out <arya-music.js> [--source <music-score.js>]')
  const src = srcAt >= 0 ? args[srcAt + 1] : fileURLToPath(new URL('../../editor/core/music-score.js', import.meta.url))
  const out = args[at + 1], bundle = bundleMusic(fs.readFileSync(src, 'utf8'))
  fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true }); fs.writeFileSync(out, bundle)
}
