import CryptoKit
import Darwin
import Foundation
import XCTest
@testable import ReelKit

private actor MusicIdentityProbeCounter {
    var calls = 0
    func mark() { calls += 1 }
    func value() -> Int { calls }
}

final class MusicIdentityBackendTests: XCTestCase {
    private var score: [String: Any] { ["version": 1, "title": "Identity QA cue", "bpm": 120, "lengthBeats": 2, "seed": 17, "room": 0, "parts": [["id": "keys", "instrument": "keys", "gainDb": -12, "pan": 0, "notes": [["at": 0.25, "duration": 1.5, "pitch": 62, "velocity": 0.7]]]]] }
    private func backend(_ root: URL) throws -> ReelBackend { try ReelBackend(folder: ProjectFolder(root: root), coreScript: Support.core()) { _, _ in } }
    private func create(_ b: ReelBackend) async throws -> (String, [String: Any]) {
        _ = try await b.handle(method: "POST", path: "/api/new", body: #"{"name":"Music identity QA"}"#)
        let version = await b.currentVersion()
        let receipt = parse(try await b.handleAssistant(method: "POST", path: "/api/audio/compose", body: JSON(any: ["score": score, "track": "A3", "start": 0, "comp": NSNull(), "expectedVersion": version]).text).text)
        XCTAssertEqual(receipt["state"] as? String, "complete")
        return (try XCTUnwrap(receipt["path"] as? String), object(receipt["asset"]))
    }
    private func mutate(_ url: URL) throws {
        let handle = try FileHandle(forUpdating: url); defer { try? handle.close() }
        try handle.seek(toOffset: 44 + 8000 * 6)
        var byte = try XCTUnwrap(handle.read(upToCount: 1)); byte[0] ^= 1
        try handle.seek(toOffset: 44 + 8000 * 6); try handle.write(contentsOf: byte)
    }
    func testNewGenerationHasActualSHAAndExactReimportRetainsItsScoreNameAndProvenance() async throws {
        let root = try Support.tempFolder("music-identity-roundtrip")
        defer { try? FileManager.default.removeItem(at: root) }
        let b = try backend(root); try await b.start()
        let (path, asset) = try await create(b), generated = object(asset["generated"]), bytes = try Data(contentsOf: root.appendingPathComponent(path))
        XCTAssertEqual(generated["contentSHA256"] as? String, SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined())
        XCTAssertEqual((generated["contentBytes"] as? NSNumber)?.intValue, bytes.count)
        let imported = parse(try await b.importMedia([path]).text), refreshed = object(object(imported["assets"])[path])
        XCTAssertEqual(refreshed["name"] as? String, "Identity QA cue")
        XCTAssertEqual(JSON(any: refreshed["generated"]).text, JSON(any: generated).text)
        XCTAssertEqual((imported["failures"] as? [Any])?.count, 0); XCTAssertEqual((imported["warnings"] as? [Any])?.count, 0)
        await b.stop()
    }
    func testSameSizeChangedMusicCannotPlaceAndReimportVisiblyRemovesGenerationMetadata() async throws {
        let root = try Support.tempFolder("music-identity-replace")
        defer { try? FileManager.default.removeItem(at: root) }
        let b = try backend(root); try await b.start()
        let (path, asset) = try await create(b), url = root.appendingPathComponent(path), before = await b.currentProject(), version = await b.currentVersion()
        let oldProbe = try NativeMusicComposer.probeOwnedWAV(folder: ProjectFolder(root: root), path: path, frames: 48000)
        try mutate(url)
        XCTAssertEqual(try NativeMusicComposer.probeOwnedWAV(folder: ProjectFolder(root: root), path: path, frames: 48000), oldProbe)
        do {
            _ = try await b.handleAssistant(method: "POST", path: "/api/audio/compose/place", body: JSON(any: ["path": path, "track": "A3", "start": 2, "comp": NSNull(), "expectedVersion": version]).text)
            XCTFail("Changed generated bytes were placed")
        } catch { XCTAssertTrue(error.localizedDescription.contains("Re-import")) }
        let afterFailedPlace = await b.currentProject(), afterVersion = await b.currentVersion()
        XCTAssertEqual(afterFailedPlace, before); XCTAssertEqual(afterVersion, version)
        let receipt = parse(try await b.importMedia([path]).text), replaced = object(object(receipt["assets"])[path])
        XCTAssertNil(replaced["generated"]); XCTAssertNil(replaced["name"])
        XCTAssertEqual(replaced["duration"] as? Double, asset["duration"] as? Double)
        let warnings = try XCTUnwrap(receipt["warnings"] as? [[String: Any]])
        XCTAssertEqual(warnings.count, 1); XCTAssertTrue((warnings[0]["message"] as? String ?? "").contains("removed its saved score"))
        await b.stop()
    }
    func testLegacyImportKeepsMediaAndHistoryWhileMixedFilesSucceedAndLegacyPlacementStillWorks() async throws {
        let root = try Support.tempFolder("music-identity-legacy")
        defer { try? FileManager.default.removeItem(at: root) }
        let b = try backend(root); try await b.start()
        let (path, asset) = try await create(b)
        var legacy = asset, generated = object(asset["generated"])
        generated.removeValue(forKey: "contentSHA256"); generated.removeValue(forKey: "contentBytes"); legacy["generated"] = generated
        _ = try await b.editOperations(ops: .array([.object([("op", "import"), ("assets", .object([(path, JSON(any: legacy))]))])]))
        let before = await b.currentProject(), version = await b.currentVersion()
        let refused = parse(try await b.importMedia([path]).text)
        XCTAssertTrue(object(refused["assets"]).isEmpty)
        let after = await b.currentProject(), afterVersion = await b.currentVersion()
        XCTAssertEqual(after, before); XCTAssertEqual(afterVersion, version)
        XCTAssertTrue(((refused["failures"] as? [[String: Any]])?.first?["error"] as? String ?? "").contains("kept unchanged"))
        try FileManager.default.copyItem(at: Support.fixture("still.png"), to: root.appendingPathComponent("ordinary.png"))
        let mixed = parse(try await b.importMedia([path, "ordinary.png"]).text)
        XCTAssertEqual(Set(object(mixed["assets"]).keys), ["ordinary.png"])
        XCTAssertEqual((mixed["failures"] as? [Any])?.count, 1)
        // Compatibility is explicit: no saved byte hash is invented for old renderer1 cues.
        try mutate(root.appendingPathComponent(path))
        let current = await b.currentVersion()
        let placed = parse(try await b.handleAssistant(method: "POST", path: "/api/audio/compose/place", body: JSON(any: ["path": path, "track": "A3", "start": 2, "comp": NSNull(), "expectedVersion": current]).text).text)
        XCTAssertEqual(placed["state"] as? String, "complete")
        XCTAssertNil(object(object(placed["asset"])["generated"])["contentSHA256"])
        await b.stop()
    }
    func testGeneratedFIFOImportAndPlaceRejectBeforeMediaProbeAndLegacyImportNeedsNoProbe() async throws {
        let root = try Support.tempFolder("music-identity-before-probe"), counter = MusicIdentityProbeCounter()
        defer { try? FileManager.default.removeItem(at: root) }
        let b = try ReelBackend(folder: ProjectFolder(root: root), coreScript: Support.core(), probe: { _ in
            await counter.mark(); throw NativeMusicComposer.Failure(message: "The media probe must not be invoked")
        }) { _, _ in }
        try await b.start()
        let (path, asset) = try await create(b), url = root.appendingPathComponent(path)
        let original = try Data(contentsOf: url)
        try FileManager.default.removeItem(at: url)
        XCTAssertEqual(url.path.withCString { Darwin.mkfifo($0, 0o600) }, 0)
        let before = await b.currentProject(), version = await b.currentVersion()
        let receipt = parse(try await b.importMedia([path]).text)
        XCTAssertTrue(object(receipt["assets"]).isEmpty); XCTAssertEqual((receipt["failures"] as? [Any])?.count, 1)
        let probes = await counter.value(); XCTAssertEqual(probes, 0)
        do {
            _ = try await b.handleAssistant(method: "POST", path: "/api/audio/compose/place", body: JSON(any: ["path": path, "track": "A3", "start": 2, "comp": NSNull(), "expectedVersion": version]).text)
            XCTFail("A FIFO reached native placement")
        } catch { XCTAssertTrue(error.localizedDescription.contains("owned regular")) }
        let after = await b.currentProject(), afterVersion = await b.currentVersion()
        XCTAssertEqual(after, before); XCTAssertEqual(afterVersion, version)
        try FileManager.default.removeItem(at: url); try original.write(to: url)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        var legacy = asset, generated = object(asset["generated"])
        generated.removeValue(forKey: "contentSHA256"); legacy["generated"] = generated
        _ = try await b.editOperations(ops: .array([.object([("op", "import"), ("assets", .object([(path, JSON(any: legacy))]))])]))
        let oldReceipt = parse(try await b.importMedia([path]).text)
        XCTAssertTrue(object(oldReceipt["assets"]).isEmpty)
        let legacyProbes = await counter.value(); XCTAssertEqual(legacyProbes, 0)
        await b.stop()
    }

}
